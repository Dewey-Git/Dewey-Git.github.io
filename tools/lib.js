/**
 * tools/lib.js —— Node 侧加密与轮换的公共实现
 * 与浏览器 assets/js/crypto.js 逐字节对齐：
 *   内容层：PBKDF2-SHA256 / 200000 次 / 32 字节 → AES-256-GCM / 12 字节 IV / 16 字节 tag
 *   分享层：HMAC-SHA256 密钥流异或封装 DEK（v9 紧凑令牌）
 */

"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const vm = require("vm");

const ITERATIONS = 200000;
const KEY_LEN = 32;
const SALT_LEN = 16;
const IV_LEN = 12;

const KEK_SALT = "card.v9.kek";
const CH_CODES = ["interview", "dating", "soul"];
const TOKEN_MAGIC = 0xb0;

const ROOT = path.resolve(__dirname, "..");
const CHANNEL_DIR = path.join(ROOT, "private", "channels");
const ROTATION_FILE = path.join(ROOT, "private", "rotation.js");

/* v15 起不再生成 private/outline.js：
 * 入口页在解锁前不展示条目名，页面上只剩一个打码的内容框，
 * 也就没有任何「分组标题 + 字段名」需要以明文发布。 */

/* 数据密钥（DEK）库：每通道一把，长期不变，只存本地、不进仓库 */
const KEYS_FILE = path.join(ROOT, "data", "keys.json");

/* ---------------- 核心加密 ---------------- */
function encryptJSON(plaintext, password, extra) {
  const salt = crypto.randomBytes(SALT_LEN);
  const iv = crypto.randomBytes(IV_LEN);

  /* extra.iter 必须同时改变真实的 KDF 次数：只改输出字段会让密文与标注不符，
   * 浏览器按标注的次数派生就会解不开（v14 踩过一次）。 */
  const iters = (extra && Number(extra.iter)) || ITERATIONS;
  const key = crypto.pbkdf2Sync(password, salt, iters, KEY_LEN, "sha256");

  const cipher = crypto.createCipheriv("aes-256-gcm", key, iv);
  const body = Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final()]);
  const ct = Buffer.concat([body, cipher.getAuthTag()]);

  return Object.assign(
    {
      v: 1,
      iter: iters,
      salt: salt.toString("base64"),
      iv: iv.toString("base64"),
      ct: ct.toString("base64")
    },
    extra || {},
    { iter: iters }
  );
}

/* ---------------- 轮换记录 ---------------- */
function loadRotation() {
  if (!fs.existsSync(ROTATION_FILE)) return {};
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync(ROTATION_FILE, "utf8"), sandbox);
  return (sandbox.window && sandbox.window.CHANNEL_ROTATION) || {};
}

function saveRotation(table) {
  const keys = Object.keys(table).sort();
  const lines = keys.map((k) => {
    const r = table[k];
    const rec = {
      keyId: r.keyId,
      issuedAt: r.issuedAt,
      scheme: r.scheme || "dek"
    };
    return (
      `  ${JSON.stringify(k)}: ` +
      JSON.stringify(rec, null, 2).replace(/\n/g, "\n  ")
    );
  });

  const content =
    `/* AUTO-GENERATED by tools/rotate.js — 请勿手工编辑 */\n` +
    `window.CHANNEL_ROTATION = {\n${lines.join(",\n")}\n};\n`;

  fs.writeFileSync(ROTATION_FILE, content, "utf8");
}

/* ---------------- 数据密钥（DEK） ---------------- */
function loadKeys() {
  if (!fs.existsSync(KEYS_FILE)) return {};
  try {
    return JSON.parse(fs.readFileSync(KEYS_FILE, "utf8")) || {};
  } catch (e) {
    throw new Error("data/keys.json 解析失败，请检查格式");
  }
}

function saveKeys(table) {
  fs.mkdirSync(path.dirname(KEYS_FILE), { recursive: true });
  fs.writeFileSync(KEYS_FILE, JSON.stringify(table, null, 2) + "\n", "utf8");
}

/** 取通道的数据密钥；不存在则生成并落盘（256 位） */
function ensureDek(channelId) {
  const table = loadKeys();
  if (!table[channelId]) {
    table[channelId] = crypto.randomBytes(32).toString("hex");
    saveKeys(table);
  }
  return table[channelId];
}

/* ---------------- 密钥处理 ---------------- */
/** 分享密钥：128 位随机（32 位十六进制） */
function generateKey() {
  return crypto.randomBytes(16).toString("hex");
}

function keyIdOf(key) {
  return crypto.createHash("sha256").update(key, "utf8").digest("hex").slice(0, 8);
}

/* ---------------- 分享层（v9） ---------------- */
/** 分享密钥 → 密钥材料。必须与浏览器 keyBytesOf 完全一致 */
function keyBytesOf(str) {
  const s = String(str == null ? "" : str);
  if (/^[0-9a-f]{32}$/i.test(s)) return Buffer.from(s, "hex");
  return crypto.pbkdf2Sync(Buffer.from(s, "utf8"), Buffer.from(KEK_SALT, "utf8"), 100000, 32, "sha256");
}

function expandStream(keyBytes, info, len) {
  let out = Buffer.alloc(0);
  let i = 1;
  while (out.length < len) {
    out = Buffer.concat([
      out,
      crypto.createHmac("sha256", keyBytes).update(Buffer.concat([info, Buffer.from([i])])).digest()
    ]);
    i += 1;
  }
  return out.subarray(0, len);
}

function tagOf(keyBytes, info, wrapped) {
  return crypto
    .createHmac("sha256", keyBytes)
    .update(Buffer.concat([Buffer.from("T", "utf8"), info, wrapped]))
    .digest()
    .subarray(0, 4);
}

function chCodeOf(id) {
  const i = CH_CODES.indexOf(id);
  return i === -1 ? 3 : i;
}

/**
 * 生成 v9 分享令牌（布局见 assets/js/crypto.js 顶部注释）
 * @param {{c:string, dek:string, key:string, ttlHours?:number, oneTime?:boolean, embed?:boolean}} opt
 */
function buildShareToken(opt) {
  const c = opt.c || "dating";
  const dekStr = String(opt.dek || "");
  if (!dekStr) throw new Error("缺少数据密钥");

  const dekHex = /^[0-9a-f]{64}$/i.test(dekStr);
  const dekBytes = dekHex ? Buffer.from(dekStr, "hex") : Buffer.from(dekStr, "utf8");
  if (!dekBytes.length || dekBytes.length > 64) throw new Error("数据密钥长度异常");

  const embed = opt.embed !== false;
  const keyBytes = keyBytesOf(opt.key);
  if (embed && keyBytes.length !== 16) throw new Error("内嵌分享密钥必须是 128 位");

  let ttlHours = Number(opt.ttlHours) || 0;
  /* 一次性令牌必须有硬性到期时间：未指定时按 1 小时签发 */
  if (opt.oneTime && !(ttlHours > 0)) ttlHours = 1;
  const expiresAt = ttlHours > 0 ? Date.now() + Math.round(ttlHours * 3600 * 1000) : 0;
  const expMin = expiresAt ? Math.max(0, Math.min(0xffffffff, Math.round(expiresAt / 60000))) : 0;

  const chCode = chCodeOf(c);
  const flags = (opt.oneTime ? 1 : 0) | (chCode << 1) | (embed ? 8 : 0);
  const head = Buffer.from([
    TOKEN_MAGIC | flags,
    (expMin >>> 24) & 0xff,
    (expMin >>> 16) & 0xff,
    (expMin >>> 8) & 0xff,
    expMin & 0xff
  ]);

  const parts = [head];
  if (chCode === 3) {
    const idBytes = Buffer.from(c, "utf8");
    parts.push(Buffer.from([idBytes.length]), idBytes);
  }
  parts.push(Buffer.from([dekBytes.length | (dekHex ? 0x80 : 0)]));

  const info = Buffer.concat(parts);
  const ks = expandStream(keyBytes, info, dekBytes.length);
  const wrapped = Buffer.alloc(dekBytes.length);
  for (let i = 0; i < dekBytes.length; i++) wrapped[i] = dekBytes[i] ^ ks[i];
  parts.push(wrapped);

  if (embed) parts.push(keyBytes);
  else parts.push(tagOf(keyBytes, info, wrapped));

  const buf = Buffer.concat(parts);
  return {
    token: buf.toString("base64url"),
    channel: c,
    expiresAt: expMin * 60000,
    oneTime: !!opt.oneTime,
    length: buf.toString("base64url").length
  };
}

/** 解开 v9 令牌；keyStr 为空时要求内嵌密钥 */
function openShareToken(token, keyStr) {
  let bytes;
  try {
    bytes = Buffer.from(String(token), "base64url");
  } catch (e) {
    throw new Error("bad-token");
  }
  if (!bytes || bytes.length < 7) throw new Error("bad-token");
  if ((bytes[0] & 0xf0) !== TOKEN_MAGIC) throw new Error("bad-token");

  const flags = bytes[0] & 0x0f;
  const oneTime = !!(flags & 1);
  const chCode = (flags >> 1) & 3;
  const hasKey = !!(flags & 8);
  const expMin = ((bytes[1] << 24) | (bytes[2] << 16) | (bytes[3] << 8) | bytes[4]) >>> 0;

  let off = 5;
  let c = CH_CODES[chCode] || "";
  if (chCode === 3) {
    const idLen = bytes[off];
    off += 1;
    c = bytes.subarray(off, off + idLen).toString("utf8");
    off += idLen;
  }

  const lenByte = bytes[off];
  off += 1;
  const dekHex = !!(lenByte & 0x80);
  const dekLen = lenByte & 0x7f;
  if (!dekLen || off + dekLen > bytes.length) throw new Error("bad-token");

  const info = bytes.subarray(0, off);
  const wrapped = bytes.subarray(off, off + dekLen);
  off += dekLen;

  let keyBytes;
  if (hasKey) {
    keyBytes = bytes.subarray(off, off + 16);
  } else {
    if (!keyStr) throw new Error("need-key");
    keyBytes = keyBytesOf(keyStr);
    const tag = bytes.subarray(off, off + 4);
    const want = tagOf(keyBytes, info, wrapped);
    if (!tag.equals(want)) throw new Error("bad-key");
  }

  const ks = expandStream(keyBytes, info, dekLen);
  const raw = Buffer.alloc(dekLen);
  for (let i = 0; i < dekLen; i++) raw[i] = wrapped[i] ^ ks[i];

  return {
    c: c || "dating",
    dek: dekHex ? raw.toString("hex") : raw.toString("utf8"),
    expiresAt: expMin * 60000,
    oneTime
  };
}

/* ---------------- v8 兼容（旧 JSON 票据） ---------------- */
function legacyUnpack(token) {
  try {
    const o = JSON.parse(Buffer.from(String(token), "base64url").toString("utf8"));
    if (!o || o.v !== 2) return null;
    if (!o.c && !o.k && !o.p) return null;
    return { c: o.c || "", k: o.k || "", p: o.p || "" };
  } catch (e) {
    return null;
  }
}

/** 旧票据：AES-256-GCM 封装的 DEK。crypto 侧用 async 版本，这里同步实现 */
function legacyOpenTicket(ticketStr, shareKey) {
  const t = JSON.parse(Buffer.from(String(ticketStr), "base64url").toString("utf8"));
  if (!t || t.v !== 1) throw new Error("票据格式不正确");
  const salt = Buffer.from(t.s, "base64");
  const iv = Buffer.from(t.i, "base64");
  const ct = Buffer.from(t.c, "base64");
  const kek = crypto.pbkdf2Sync(shareKey, salt, ITERATIONS, KEY_LEN, "sha256");
  const decipher = crypto.createDecipheriv("aes-256-gcm", kek, iv);
  decipher.setAuthTag(ct.subarray(ct.length - 16));
  const plain = Buffer.concat([decipher.update(ct.subarray(0, ct.length - 16)), decipher.final()]);
  return { dek: plain.toString("utf8"), expiresAt: Number(t.e) || 0, oneTime: !!t.o };
}

/* ---------------- 主流程 ---------------- */
function rotateChannel(opts) {
  const channelId = opts.channelId;
  const inputPath = opts.inputPath || path.join("data", `${channelId}.json`);

  const absInput = path.resolve(ROOT, inputPath);
  if (!fs.existsSync(absInput)) {
    throw new Error(`找不到明文文件：${inputPath}`);
  }

  const plaintext = fs.readFileSync(absInput, "utf8");
  const parsed = JSON.parse(plaintext); // 校验 JSON，同时用于生成大纲

  /* 数据密钥：显式指定则覆盖并记录，否则沿用已有 / 首次生成 */
  const existing = loadKeys()[channelId];
  let dek;
  if (opts.key) {
    dek = opts.key;
    const table = loadKeys();
    table[channelId] = dek;
    saveKeys(table);
  } else {
    dek = ensureDek(channelId);
  }

  const keyId = keyIdOf(dek);
  const payload = encryptJSON(plaintext, dek, { keyId, scheme: "dek" });

  fs.mkdirSync(CHANNEL_DIR, { recursive: true });
  const outFile = path.join(CHANNEL_DIR, `${channelId}.enc.js`);
  fs.writeFileSync(
    outFile,
    `/* AUTO-GENERATED by tools/rotate.js — 请勿手工编辑 */\n` +
      `/* channel: ${channelId} · keyId: ${keyId} · ${new Date().toISOString()} */\n` +
      `window.PRIVATE_CHANNELS = window.PRIVATE_CHANNELS || {};\n` +
      `window.PRIVATE_CHANNELS[${JSON.stringify(channelId)}] = ` +
      JSON.stringify(payload, null, 2) +
      ";\n",
    "utf8"
  );

  const table = loadRotation();
  table[channelId] = {
    keyId: keyId,
    issuedAt: new Date().toISOString(),
    scheme: "dek"
  };
  saveRotation(table);

  return {
    channelId,
    dek,
    keyId,
    dekCreated: !existing,
    outFile: path.relative(ROOT, outFile),
    rotationFile: path.relative(ROOT, ROTATION_FILE),
    keysFile: path.relative(ROOT, KEYS_FILE)
  };
}


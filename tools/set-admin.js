#!/usr/bin/env node
/**
 * ============================================================
 * tools/set-admin.js —— 设置 / 更换管理员密码
 * ------------------------------------------------------------
 * 用法：
 *   node tools/set-admin.js "你的管理员密码"
 *
 * 说明：
 *   · 只写入密文 private/admin.vault.js，明文密码不落盘、不进仓库
 *   · 该密码仅用于「密钥管理」的操作授权，不参与任何数据解密
 *   · 忘记密码无法找回，重新执行本命令即可覆盖
 * ============================================================
 */

"use strict";

const fs = require("fs");
const path = require("path");
const lib = require("./lib");

const password = process.argv[2];

if (!password) {
  console.log('用法：node tools/set-admin.js "你的管理员密码"');
  process.exit(1);
}

if (password.length < 10) {
  console.error("✗ 管理员密码至少 10 位，建议 14 位以上并混合大小写与符号。");
  process.exit(1);
}

/* 把各通道的数据密钥一并封进 vault：
   管理台凭管理员密码解出 DEK，才能在浏览器里现场签发分享票据。
   DEK 本身仍只以密文形式存在于 admin.vault.js，明文只在 data/keys.json（本地）。 */
const keys = lib.loadKeys();
const keyIds = Object.keys(keys).sort();

const payload = lib.encryptJSON(
  JSON.stringify({
    ok: true,
    scope: "admin-gate",
    keys: keys,
    createdAt: new Date().toISOString()
  }),
  password,
  { kind: "admin-vault" }
);

const outFile = path.join(lib.ROOT, "private", "admin.vault.js");

fs.writeFileSync(
  outFile,
  `/* AUTO-GENERATED by tools/set-admin.js — 请勿手工编辑 */\n` +
    `/* 仅存放校验密文与数据密钥密文，不含任何明文密码 */\n` +
    `window.ADMIN_VAULT = ${JSON.stringify(payload, null, 2)};\n`,
  "utf8"
);

console.log(`
✓ 管理员密码已设置
  密文文件 : ${path.relative(lib.ROOT, outFile)}
  迭代次数 : ${payload.iter}
  已封装密钥: ${keyIds.length ? keyIds.join(", ") : "（无，先运行 rotate.js 生成）"}
${keyIds.length ? "" : "  ⚠ 没有数据密钥，管理台将无法签发分享链接。\n"}
提醒：
  · 请记住该密码，忘记后只能重新执行本命令覆盖
  · 每次新增通道或更换数据密钥后，需要重新执行本命令
  · 终端历史中可能残留密码，建议清理
`);
